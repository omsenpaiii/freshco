ALTER TABLE public.blog_posts ALTER COLUMN author SET DEFAULT 'FreshCo Deli';

ALTER TABLE public.products
  ADD COLUMN IF NOT EXISTS brand TEXT NOT NULL DEFAULT '',
  ADD COLUMN IF NOT EXISTS unit TEXT NOT NULL DEFAULT 'EA',
  ADD COLUMN IF NOT EXISTS subcategory_1 TEXT NOT NULL DEFAULT '',
  ADD COLUMN IF NOT EXISTS subcategory_2 TEXT NOT NULL DEFAULT '',
  ADD COLUMN IF NOT EXISTS status TEXT NOT NULL DEFAULT 'draft',
  ADD COLUMN IF NOT EXISTS image_match_status TEXT NOT NULL DEFAULT 'unverified',
  ADD COLUMN IF NOT EXISTS product_source_url TEXT,
  ADD COLUMN IF NOT EXISTS image_source_url TEXT,
  ADD COLUMN IF NOT EXISTS draft_reason TEXT;

ALTER TABLE public.products DROP CONSTRAINT IF EXISTS products_status_check;
ALTER TABLE public.products ADD CONSTRAINT products_status_check
  CHECK (status IN ('draft', 'published'));
ALTER TABLE public.products DROP CONSTRAINT IF EXISTS products_image_match_status_check;
ALTER TABLE public.products ADD CONSTRAINT products_image_match_status_check
  CHECK (image_match_status IN ('unverified', 'verified'));

CREATE TABLE IF NOT EXISTS public.product_variants (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id BIGINT NOT NULL REFERENCES public.products(id) ON DELETE CASCADE,
  title TEXT NOT NULL,
  sku TEXT NOT NULL UNIQUE,
  weight_grams INTEGER CHECK (weight_grams IS NULL OR weight_grams > 0),
  price NUMERIC(10,2) NOT NULL CHECK (price >= 0),
  inventory_quantity INTEGER NOT NULL DEFAULT 0 CHECK (inventory_quantity >= 0),
  is_default BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (product_id, title)
);

CREATE UNIQUE INDEX IF NOT EXISTS one_default_variant_per_product
  ON public.product_variants(product_id) WHERE is_default;
CREATE INDEX IF NOT EXISTS product_variants_product_id_idx
  ON public.product_variants(product_id);

ALTER TABLE public.product_variants ENABLE ROW LEVEL SECURITY;

ALTER TABLE public.cart_items
  ADD COLUMN IF NOT EXISTS variant_id BIGINT REFERENCES public.product_variants(id) ON DELETE CASCADE;
ALTER TABLE public.order_items
  ADD COLUMN IF NOT EXISTS variant_id BIGINT REFERENCES public.product_variants(id) ON DELETE SET NULL,
  ADD COLUMN IF NOT EXISTS variant_title TEXT,
  ADD COLUMN IF NOT EXISTS sku TEXT;

ALTER TABLE public.cart_items DROP CONSTRAINT IF EXISTS cart_items_profile_id_product_id_key;
CREATE UNIQUE INDEX IF NOT EXISTS cart_items_profile_product_variant_key
  ON public.cart_items(profile_id, product_id, variant_id);
CREATE INDEX IF NOT EXISTS cart_items_variant_id_idx ON public.cart_items(variant_id);
CREATE INDEX IF NOT EXISTS order_items_variant_id_idx ON public.order_items(variant_id);
CREATE INDEX IF NOT EXISTS products_catalog_filter_idx
  ON public.products(category_id, status, brand, subcategory_1, subcategory_2);

DROP POLICY IF EXISTS "Allow public read access to products" ON public.products;
DROP POLICY IF EXISTS "Allow all access for service role on products" ON public.products;
CREATE POLICY "Published products are publicly readable" ON public.products
  FOR SELECT TO anon, authenticated
  USING (status = 'published');

CREATE POLICY "Published product variants are publicly readable" ON public.product_variants
  FOR SELECT TO anon, authenticated
  USING (EXISTS (
    SELECT 1 FROM public.products
    WHERE products.id = product_variants.product_id
      AND products.status = 'published'
  ));

DROP POLICY IF EXISTS "Allow all access for service role on categories" ON public.categories;
DROP POLICY IF EXISTS "Allow all access for service role on blog posts" ON public.blog_posts;
DROP POLICY IF EXISTS "Allow public read access to profiles" ON public.profiles;
CREATE POLICY "Users can read their own profile" ON public.profiles
  FOR SELECT TO authenticated USING ((SELECT auth.uid()) = id);

-- New Supabase projects require explicit Data API grants in addition to RLS.
