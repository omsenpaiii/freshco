GRANT ALL ON TABLE public.products, public.product_variants, public.categories TO service_role;
GRANT ALL ON ALL SEQUENCES IN SCHEMA public TO service_role;

CREATE OR REPLACE FUNCTION public.touch_product_variant_updated_at()
RETURNS TRIGGER LANGUAGE plpgsql SET search_path = '' AS $$
BEGIN
  NEW.updated_at = NOW();
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS touch_product_variant_updated_at ON public.product_variants;
CREATE TRIGGER touch_product_variant_updated_at
  BEFORE UPDATE ON public.product_variants
  FOR EACH ROW EXECUTE FUNCTION public.touch_product_variant_updated_at();
REVOKE ALL ON FUNCTION public.touch_product_variant_updated_at() FROM PUBLIC;

CREATE OR REPLACE FUNCTION public.refresh_category_product_counts()
RETURNS VOID LANGUAGE sql SECURITY DEFINER SET search_path = '' AS $$
  UPDATE public.categories c
  SET products_count = (
    SELECT COUNT(*) FROM public.products p
    WHERE p.category_id = c.id AND p.status = 'published'
  );
$$;
REVOKE ALL ON FUNCTION public.refresh_category_product_counts() FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.refresh_category_product_counts() TO service_role;
