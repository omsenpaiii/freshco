CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE TABLE IF NOT EXISTS categories (
  id BIGINT PRIMARY KEY, name TEXT NOT NULL, slug TEXT UNIQUE NOT NULL,
  description TEXT, image_url TEXT, image_source_url TEXT, image_license TEXT,
  products_count INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS products (
  id BIGINT PRIMARY KEY, name TEXT NOT NULL, slug TEXT UNIQUE NOT NULL,
  description TEXT, price NUMERIC(10,2) NOT NULL CHECK (price >= 0),
  compare_at_price NUMERIC(10,2), sku TEXT, inventory_quantity INTEGER NOT NULL DEFAULT 0,
  is_featured BOOLEAN NOT NULL DEFAULT false, is_trending BOOLEAN NOT NULL DEFAULT false,
  images TEXT[] NOT NULL DEFAULT '{}', category_id BIGINT REFERENCES categories(id) ON DELETE SET NULL,
  brand TEXT NOT NULL DEFAULT '', unit TEXT NOT NULL DEFAULT 'EA',
  subcategory_1 TEXT NOT NULL DEFAULT '', subcategory_2 TEXT NOT NULL DEFAULT '',
  status TEXT NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','published')),
  image_match_status TEXT NOT NULL DEFAULT 'unverified' CHECK (image_match_status IN ('unverified','verified')),
  product_source_url TEXT, image_source_url TEXT, image_license TEXT, storage_object_key TEXT,
  draft_reason TEXT, source_active BOOLEAN NOT NULL DEFAULT false,
  source_workbook TEXT, source_row INTEGER, source_item_name TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS product_variants (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id BIGINT NOT NULL REFERENCES products(id) ON DELETE CASCADE,
  title TEXT NOT NULL, sku TEXT NOT NULL UNIQUE, weight_grams INTEGER CHECK (weight_grams IS NULL OR weight_grams > 0),
  price NUMERIC(10,2) NOT NULL CHECK (price >= 0), inventory_quantity INTEGER NOT NULL DEFAULT 0 CHECK (inventory_quantity >= 0),
  is_default BOOLEAN NOT NULL DEFAULT false, image_url TEXT, image_source_url TEXT, image_license TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE(product_id,title)
);
CREATE UNIQUE INDEX IF NOT EXISTS one_default_variant_per_product ON product_variants(product_id) WHERE is_default;
CREATE INDEX IF NOT EXISTS products_catalog_filter_idx ON products(category_id,status,brand,subcategory_1,subcategory_2);
CREATE UNIQUE INDEX IF NOT EXISTS products_source_row_idx ON products(source_workbook,source_row) WHERE source_workbook IS NOT NULL;
CREATE INDEX IF NOT EXISTS product_variants_product_id_idx ON product_variants(product_id);

CREATE TABLE IF NOT EXISTS profiles (
  id TEXT PRIMARY KEY, email TEXT UNIQUE NOT NULL, full_name TEXT, created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS addresses (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(), profile_id TEXT NOT NULL REFERENCES profiles(id) ON DELETE CASCADE,
  address_line_1 TEXT NOT NULL, address_line_2 TEXT, city TEXT NOT NULL, state TEXT NOT NULL,
  postal_code TEXT NOT NULL, country TEXT NOT NULL DEFAULT 'Australia', phone TEXT,
  is_default BOOLEAN NOT NULL DEFAULT false, created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS cart_items (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(), profile_id TEXT NOT NULL REFERENCES profiles(id) ON DELETE CASCADE,
  product_id BIGINT NOT NULL REFERENCES products(id) ON DELETE CASCADE,
  variant_id BIGINT NOT NULL REFERENCES product_variants(id) ON DELETE CASCADE,
  quantity INTEGER NOT NULL CHECK(quantity > 0), created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE(profile_id,product_id,variant_id)
);
CREATE TABLE IF NOT EXISTS wishlist_items (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(), profile_id TEXT NOT NULL REFERENCES profiles(id) ON DELETE CASCADE,
  product_id BIGINT NOT NULL REFERENCES products(id) ON DELETE CASCADE, created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE(profile_id,product_id)
);
CREATE TABLE IF NOT EXISTS blog_posts (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(), title TEXT NOT NULL, slug TEXT UNIQUE NOT NULL,
  content TEXT NOT NULL, excerpt TEXT, author TEXT NOT NULL DEFAULT 'FreshCo Deli', image_url TEXT,
  published_at TIMESTAMPTZ NOT NULL DEFAULT now(), created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS blog_comments (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(), post_id UUID NOT NULL REFERENCES blog_posts(id) ON DELETE CASCADE,
  author_name TEXT NOT NULL, author_email TEXT NOT NULL, content TEXT NOT NULL, created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS orders (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(), profile_id TEXT REFERENCES profiles(id) ON DELETE SET NULL,
  total_amount NUMERIC(10,2) NOT NULL, status TEXT NOT NULL DEFAULT 'pending',
  shipping_name TEXT NOT NULL, shipping_email TEXT NOT NULL, shipping_address TEXT NOT NULL,
  shipping_city TEXT NOT NULL, shipping_state TEXT NOT NULL, shipping_postal_code TEXT NOT NULL,
  shipping_country TEXT NOT NULL DEFAULT 'Australia', stripe_checkout_session_id TEXT UNIQUE,
  stripe_payment_intent_id TEXT, currency TEXT NOT NULL DEFAULT 'aud',
  payment_status TEXT NOT NULL DEFAULT 'unpaid' CHECK(payment_status IN ('unpaid','paid','failed','expired','refunded')),
  paid_at TIMESTAMPTZ, created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS order_items (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(), order_id UUID NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
  product_id BIGINT REFERENCES products(id) ON DELETE SET NULL, variant_id BIGINT REFERENCES product_variants(id) ON DELETE SET NULL,
  variant_title TEXT, sku TEXT, quantity INTEGER NOT NULL CHECK(quantity > 0), price NUMERIC(10,2) NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS order_items_order_id_idx ON order_items(order_id);
CREATE INDEX IF NOT EXISTS orders_profile_id_idx ON orders(profile_id);

CREATE OR REPLACE FUNCTION refresh_category_product_counts() RETURNS void LANGUAGE sql AS $$
  UPDATE categories c SET products_count=(SELECT count(*) FROM products p WHERE p.category_id=c.id AND p.status='published');
$$;

CREATE OR REPLACE FUNCTION complete_stripe_order(p_order_id UUID,p_session_id TEXT,p_payment_intent_id TEXT DEFAULT NULL)
RETURNS BOOLEAN LANGUAGE plpgsql AS $$
DECLARE current_status TEXT; line RECORD;
BEGIN
  SELECT payment_status INTO current_status FROM orders WHERE id=p_order_id AND stripe_checkout_session_id=p_session_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Stripe order/session mismatch'; END IF;
  IF current_status='paid' THEN RETURN true; END IF;
  FOR line IN SELECT variant_id,quantity FROM order_items WHERE order_id=p_order_id ORDER BY id LOOP
    UPDATE product_variants SET inventory_quantity=inventory_quantity-line.quantity,updated_at=now()
    WHERE id=line.variant_id AND inventory_quantity>=line.quantity;
    IF NOT FOUND THEN RAISE EXCEPTION 'Insufficient inventory for variant %',line.variant_id; END IF;
  END LOOP;
  UPDATE products p SET inventory_quantity=v.qty FROM (
    SELECT product_id,sum(inventory_quantity)::integer qty FROM product_variants
    WHERE product_id IN (SELECT DISTINCT product_id FROM order_items WHERE order_id=p_order_id) GROUP BY product_id
  ) v WHERE p.id=v.product_id;
  UPDATE orders SET payment_status='paid',status='processing',stripe_payment_intent_id=p_payment_intent_id,paid_at=now(),updated_at=now() WHERE id=p_order_id;
  RETURN true;
END; $$;
